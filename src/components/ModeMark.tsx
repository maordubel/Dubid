/**
 * components/ModeMark.tsx — הסמל של כל מצב משחק.
 *
 * ═══════════════════════════════════════════════════════════════
 * ★ למה SVG ולא עוד שני קבצי PNG
 * ═══════════════════════════════════════════════════════════════
 *
 * הסמלים האלה מופיעים בעשרה גדלים — מתג של 18px בניווט ועד
 * 240px בכרטיס השיתוף — ובשלושה צבעים. PNG היה אומר שלושים
 * קבצים, או שישה קבצים מטושטשים.
 *
 * חשוב מזה: הם צריכים לקבל את **צבע המצב** (`currentColor`).
 * PNG לא יכול.
 *
 * שניהם יחד שוקלים פחות מקילובייט אחד, ואין להם בקשת רשת בכלל.
 *
 * ═══════════════════════════════════════════════════════════════
 * ★ למה הם נראים ככה
 * ═══════════════════════════════════════════════════════════════
 *
 * הלוגו הראשי הוא **קו אחד**, במשקל אחיד, בלי מילוי. הסמלים
 * האלה חייבים להיראות כאילו אותה יד ציירה אותם — אחרת המוצר
 * נראה כמו שני מותגים.
 *
 * לכן: `fill="none"`, `stroke-width` אחיד, `stroke-linecap="round"`,
 * ואפס משטחים מלאים. אותה שפה, שני משפטים.
 *
 *   דוביד 5   — פאנל מחומש של כדור, עם ספרה 5 חתוכה מתוך הקו,
 *               ושני קווי תנועה. הכדור של הרחוב, בבעיטה.
 *
 *   דוביד 11  — לוח הטקטיקה של המאמן: מסגרת, קו אמצע, ואחת־עשרה
 *               נקודות במערך 4-3-3. ★ זה הקישור הישיר ללוגו —
 *               הלוח שהמאמן מחזיק ביד הוא בדיוק הדבר הזה.
 */

export interface ModeMarkProps {
  size?: number;
  /** עובי הקו ביחידות ה-viewBox (64). ברירת המחדל תואמת ללוגו. */
  weight?: number;
  className?: string;
  /** ריק = דקורטיבי. הסמל כמעט תמיד יושב ליד שם המצב. */
  alt?: string;
}

/* ================================================================== */

/**
 * דוביד 5 — הכדור של הרחוב.
 *
 * ★ הספרה 5 היא **חלק מהקו**, לא טקסט מעל.
 *   `<text>` ב-SVG תלוי בפונט שהמשכתב לא בהכרח יטען, ואז הסמל
 *   נראה אחרת אצל כל אחד. נתיב הוא נתיב.
 */
export function ModeMarkFive({
  size = 40, weight = 2.4, className = '', alt = '',
}: ModeMarkProps) {
  /* ★ מתחת ל-30px התפרים הופכים לרעש.
     סמל שנקרא ב-22px חשוב יותר מסמל שנאמן לחלוטין ב-22px. */
  const compact = size < 30;
  return (
    <svg
      viewBox="0 0 64 64"
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      strokeWidth={weight}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={`block shrink-0 ${className}`}
      role={alt ? 'img' : undefined}
      aria-label={alt || undefined}
      aria-hidden={alt ? undefined : true}
    >
      {/* פאנל מחומש — הצורה שכולם מזהים ככדורגל, בקו אחד */}
      <path d="M32 9 L54.4 25.3 L45.8 51.7 L18.2 51.7 L9.6 25.3 Z" />

      {/* תפרים קצרים החוצה מהקודקודים — הכדור התפור של פעם */}
      {!compact && (
        <g opacity=".85">
          <path d="M32 9 V3.4" />
          <path d="M54.4 25.3 L59.7 23.6" />
          <path d="M45.8 51.7 L49.1 56.3" />
          <path d="M18.2 51.7 L14.9 56.3" />
          <path d="M9.6 25.3 L4.3 23.6" />
        </g>
      )}

      {/* ★ הספרה 5, בקו. שלושה קטעים: גג, גב, ובטן. */}
      <path d="M36.6 22.6 H27.6 L26.4 31.4
               C29.6 29.3 34.6 29.4 36.8 32.1
               C39.4 35.3 38.6 40.6 34.8 42.6
               C31.4 44.4 27.3 43.4 25.6 40.4" />
    </svg>
  );
}

/* ================================================================== */

/**
 * דוביד 11 — לוח הטקטיקה.
 *
 * ★ אחת־עשרה נקודות, במערך 4-3-3, ולא "כמה נקודות".
 *   מי שסופר — ימצא אחת־עשרה. סמל של משחק שכל כולו מספר מדויק
 *   חייב להחזיק את המספר.
 */
export function ModeMarkFull({
  size = 40, weight = 2.4, className = '', alt = '',
}: ModeMarkProps) {
  /* GK · הגנה 4 · קישור 3 · חלוץ 3 — משמאל לימין בכל שורה. */
  const dots: Array<[number, number]> = [
    [32, 55],                                       // שוער
    [12, 47], [24, 48], [40, 48], [52, 47],         // הגנה
    [18, 36], [32, 38], [46, 36],                   // קישור
    [16, 18], [32, 14.5], [48, 18],                 // התקפה
  ];

  /* ★ באותו היגיון: ב-22px קו האמצע, העיגול והרחבה מתמזגים
     לכתם. אחת־עשרה הנקודות הן מה שאומר "הרכב" — הן נשארות. */
  const compact = size < 30;

  return (
    <svg
      viewBox="0 0 64 64"
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      strokeWidth={weight}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={`block shrink-0 ${className}`}
      role={alt ? 'img' : undefined}
      aria-label={alt || undefined}
      aria-hidden={alt ? undefined : true}
    >
      {/* המסגרת של הלוח */}
      <rect x="5" y="4" width="54" height="56" rx="5" />

      {!compact && (
        <g opacity=".55">
          {/* קו האמצע ועיגול הפתיחה */}
          <path d="M5 27.5 H59" />
          <circle cx="32" cy="27.5" r="6.4" />
          {/* רחבת השוער — הקו שהופך מלבן למגרש */}
          <path d="M22 60 V52 H42 V60" />
        </g>
      )}

      {/* ★ אחת־עשרה. `r` קטן ו-fill מלא: נקודה, לא טבעת —
          אחרת ב-24px הן נראות כמו רעש. */}
      <g fill="currentColor" stroke="none">
        {dots.map(([cx, cy], i) => (
          <circle key={i} cx={cx} cy={cy} r={weight * 1.15} />
        ))}
      </g>
    </svg>
  );
}

/* ================================================================== */

/** בורר. מקום אחד שיודע איזה סמל שייך לאיזה מצב. */
export function ModeMark({
  mode, ...rest
}: ModeMarkProps & { mode: 'five' | 'full' }) {
  return mode === 'five' ? <ModeMarkFive {...rest} /> : <ModeMarkFull {...rest} />;
}
