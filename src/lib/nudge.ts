/**
 * lib/nudge.ts — מתי מציעים לאורח להירשם.
 *
 * ═══════════════════════════════════════════════════════════════
 * ★ למה זה קובץ נפרד מהקומפוננטה
 * ═══════════════════════════════════════════════════════════════
 *
 * אותה סיבה בדיוק כמו `growth.ts`: **החלטה נבדקת, ציור לא.**
 * `node --experimental-strip-types` לא טוען `.tsx` בכלל, ולכן
 * כלל שחי בתוך קומפוננטה הוא כלל שאין עליו בדיקה — וזה בדיוק
 * הסוג של כלל שנשחק בשקט עד שהמוצר מציק למשתמשים.
 *
 * כאן: פונקציה טהורה, בלי DOM ובלי שעון.
 *
 * ═══════════════════════════════════════════════════════════════
 * ★ הכלל: מציעים רק למי שיש לו מה לאבד
 * ═══════════════════════════════════════════════════════════════
 *
 * אורח שנכנס עכשיו ועוד לא בחר שחקן אחד לא מסכן כלום. הצעה
 * להירשם באותו רגע היא מס כניסה — בדיוק מה שהמוצר החליט לא
 * לגבות. אותה הצעה בדיוק, אחרי שהוא הגיש הרכב, מתארת סיכון
 * אמיתי: ההרכב הזה חי בדפדפן אחד.
 *
 * שימו לב למה ש**אין** כאן: ספירת כניסות, "כל פעם שלישית",
 * או השהיה. כל אלה הופכים את ההצעה למשהו שקורה *למשתמש* במקום
 * למשהו שנובע ממה שהוא עשה.
 */

export interface NudgeContext {
  /** אורח = אין חשבון ואין קישור לאופסיידס. */
  isGuest: boolean;
  /** האם המשתמש כבר הגיש הרכב במחזור הזה. */
  hasSubmitted: boolean;
  /** האם התוצאות פורסמו — אחרי פרסום, יש גם דירוג לאבד. */
  published: boolean;
  gameweekNumber: number;
  /** המחזור שבו המשתמש סגר את ההצעה, אם סגר. */
  dismissedForGameweek: number | null;
}

/** ההחלטה, בשורה אחת: יש מה לאבד, ואף אחד לא ביקש שקט. */
export function shouldNudge(ctx: NudgeContext): boolean {
  if (!ctx.isGuest) return false;
  if (ctx.dismissedForGameweek === ctx.gameweekNumber) return false;
  return ctx.hasSubmitted || ctx.published;
}

/** המפתח שבו נשמרת הסגירה. חשוף כדי שהבדיקה לא תנחש אותו. */
export const NUDGE_DISMISS_KEY = 'dubid.nudge.dismissed.v1';

