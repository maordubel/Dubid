/**
 * ★★ ההצעה הזו מופיעה **פעם אחת**, ולא פעם במחזור ★★
 *
 * ההבדל מ-`shouldNudge` הוא מהותי ולא כמותי:
 *
 *   הצעת ההרשמה   רצועה בתוך הדף. אפשר לגלול מעליה. חוזרת כל
 *                 מחזור כי בכל מחזור יש משהו חדש לאבד.
 *
 *   כרטיס המנוי   מסך מלא, שקופץ מעצמו. **חוסם רגע אחד** של
 *                 המשתמש, ולכן מותר לו לעשות את זה פעם אחת
 *                 בחיים ולא פעם בשבוע.
 *
 * מסך שקופץ מעצמו בכל מחזור, גם אם הוא נדיב, נקרא כהטרדה —
 * ואז גם ההצעה עצמה מפסידה. אחרי הפעם הראשונה הכרטיס נשאר
 * זמין תמיד מ"החשבון שלי", והמשתמש מגיע אליו כשהוא רוצה.
 *
 * ★ למה גם `hasSubmitted` וגם `isGuest`
 *   אורח שעוד לא הגיש לא בנה כלום, ואין לו מה להגן עליו.
 *   משתמש רשום כבר יכול להיכנס עם המייל שלו — כרטיס אצלו הוא
 *   פתרון לבעיה שאין לו.
 */
export interface PassOfferContext {
  isGuest: boolean;
  hasSubmitted: boolean;
  /** האם כבר הוצע פעם. */
  offeredBefore: boolean;
  /** האם המשתמש כבר מחזיק מפתח. */
  hasPass: boolean;
}

export function shouldOfferPass(ctx: PassOfferContext): boolean {
  if (!ctx.isGuest) return false;
  if (!ctx.hasSubmitted) return false;
  if (ctx.offeredBefore) return false;
  if (ctx.hasPass) return false;
  return true;
}

