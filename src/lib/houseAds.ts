/**
 * מחזיר רשימת בעיות בעברית. ריק = תקין.
 *
 * ★ אותה פונקציה נקראת גם בטופס וגם לפני השמירה, ולכן אי אפשר
 *   להגיע למצב שבו הטופס מרשה משהו שהשרת דוחה.
 */
export function adIssues(ad: Partial<HouseAd>): string[] {
  const out: string[] = [];
  if (!ad.headline?.trim()) out.push('חסרה כותרת');
  if ((ad.headline?.length ?? 0) > 60) out.push('הכותרת ארוכה מדי (עד 60 תווים)');
  if ((ad.body?.length ?? 0) > 120) out.push('הגוף ארוך מדי (עד 120 תווים)');
  if (!ad.cta?.trim()) out.push('חסרה קריאה לפעולה');
  if (!ad.brand || !(ad.brand in BRANDS)) out.push('מותג לא מוכר');
  if ((ad.weight ?? 0) < 1 || (ad.weight ?? 0) > 10) out.push('משקל חייב להיות בין 1 ל-10');

  if (ad.url) {
    try {
      const u = new URL(ad.url);
      if (u.protocol !== 'https:') out.push('הקישור חייב להיות https');
    } catch {
      out.push('הקישור אינו כתובת תקינה');
    }
  } else {
    out.push('חסר קישור');
  }

  if (ad.startsAt && ad.endsAt) {
    const a = Date.parse(ad.startsAt);
    const b = Date.parse(ad.endsAt);
    if (!Number.isNaN(a) && !Number.isNaN(b) && b <= a) {
      out.push('תאריך הסיום מוקדם מתאריך ההתחלה');
    }
  }
  return out;
}
