/**
 * בונה את הקישור עם שיוך מלא.
 *
 * המוצר השני יודע בדיוק מאיפה הגיע המשתמש, מאיזה מסך, איזו
 * מודעה ואיזה מחזור — **בלי שום מזהה אישי בכתובת** ובלי קוקי
 * צד־שלישי. זו הסיבה שהפרמטרים האלה נבנים כאן במקום אחד ולא
 * מודבקים ידנית בכל קומפוננטה.
 */
export function houseUrl(
  ad: HouseAd, placement: Placement, gameweekNumber: number,
): string {
  try {
    const url = new URL(ad.url);
    url.searchParams.set('ref', 'dubid');
    url.searchParams.set('src', placement);
    url.searchParams.set('v', ad.id);
    url.searchParams.set('gw', String(gameweekNumber));
    return url.toString();
  } catch {
    /* כתובת פגומה שהוקלדה בלוח הניהול לא מפילה את המסך. */
    return BRANDS[ad.brand]?.url ?? DUBEL.site;
  }
}

