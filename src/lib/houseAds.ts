/**
 * האם המודעה בחלון התצוגה שלה.
 *
 * ★ תאריך פגום = לא מוצג, ולא "מוצג תמיד".
 *   מודעת קמפיין שפג תוקפו וממשיכה לרוץ כי מישהו הקליד תאריך
 *   שגוי היא בדיוק סוג התקלה שאף אחד לא מבחין בה חודשיים.
 */
export function inWindow(ad: HouseAd, nowMs: number): boolean {
  if (ad.startsAt) {
    const t = Date.parse(ad.startsAt);
    if (Number.isNaN(t) || nowMs < t) return false;
  }
  if (ad.endsAt) {
    const t = Date.parse(ad.endsAt);
    if (Number.isNaN(t) || nowMs > t) return false;
  }
  return true;
}

/**
 * המודעות שמותר להציג במסך נתון, בסדר יציב.
 *
 * המיון לפי `id` הוא מה שהופך את הסבב לניתן לשחזור גם כשהמסד
 * מחזיר שורות בסדר אחר בכל קריאה.
 */
export function eligibleAds(
  ads: HouseAd[], placement: Placement, nowMs: number,
): HouseAd[] {
  return ads
    .filter((a) => a.enabled
      && a.weight > 0
      && (a.placements.length === 0 || a.placements.includes(placement))
      && inWindow(a, nowMs))
    .slice()
    .sort((a, b) => a.id.localeCompare(b.id));
}

/**
 * פורש את המשקלים לרשימה שאפשר לעבור עליה במחזוריות.
 *
 * ★ שזירה, ולא [א,א,א,ב,ב].
 *
 * פרישה נאיבית מציגה את אותה מודעה שלוש פעמים ברצף ואז עוברת.
 * למשתמש זה נראה כמו תקלה, ובפועל זו בדיוק החשיפה החוזרת
 * שהסבב נועד למנוע. השזירה שומרת על היחס לאורך זמן ומפזרת
 * אותו בזמן קצר.
 *
 * ★★ מתי בכל זאת תהיה חזרה, ולמה לא "תיקנו" אותה ★★
 *
 * חזרה צמודה אפשרית **רק** כאשר משקל של מודעה אחת גדול מסכום
 * כל השאר ועוד אחת — למשל 10 מול 1. במצב כזה אין סידור בלי
 * חזרה, וזו עובדה מתמטית ולא באג.
 *
 * הפיתוי היה לגזום את המשקל הדומיננטי כדי לאכוף "אף פעם לא
 * פעמיים ברצף". נדחה בכוונה: אדמין שכתב 10 מול 1 ביקש
 * במפורש שמודעה אחת תשלוט, וגזימה שקטה של הבקשה שלו היא
 * מערכת שלא עושה מה שכתוב בה. במקום זה האלגוריתם הזה
 * (חמדן, "הכי הרבה שנותר ולא הקודמת") הוא **אופטימלי**: הוא
 * מייצר את מספר החזרות המינימלי האפשרי לכל צירוף משקלים.
 */
export function rotation(ads: HouseAd[]): HouseAd[] {
  if (ads.length <= 1) return ads.slice();

  const left = ads.map((ad) => ({ ad, remaining: Math.min(10, Math.max(1, ad.weight)) }));
  const out: HouseAd[] = [];
  let guard = 0;

  while (left.some((x) => x.remaining > 0) && guard++ < 200) {
    // בכל סבב: המודעה עם הכי הרבה שנותר, אבל לא זו שהוצגה זה עתה.
    const prev = out[out.length - 1];
    const pool = left.filter((x) => x.remaining > 0);
    const candidates = pool.filter((x) => x.ad.id !== prev?.id);
    const from = candidates.length > 0 ? candidates : pool;
    const best = from.reduce((a, b) => (b.remaining > a.remaining ? b : a));
    best.remaining -= 1;
    out.push(best.ad);
  }
  return out;
}

/** גיבוב יציב למחרוזת. אותו קלט → אותו מספר, בכל מכשיר. */
export function seedOf(s: string): number {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

/**
 * המודעה שצריך להציג.
 *
 * `tick` הוא מונה שעולה באחד בכל החלפה. `seed` מזיז את נקודת
 * ההתחלה לפי המסך והמחזור, כדי ששני מסכים באותו ביקור לא
 * יציגו בדיוק את אותה מודעה.
 */
export function adAt(
  ads: HouseAd[], seed: number, tick: number,
): HouseAd | null {
  const seq = rotation(ads);
  if (seq.length === 0) return null;
  const i = (((seed % seq.length) + (tick % seq.length)) % seq.length + seq.length) % seq.length;
  return seq[i];
}

