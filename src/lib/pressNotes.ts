/**
 * שורת בית הדפוס. קבועה, ולכן היא המותג ולא הבדיחה.
 *
 * ★ העיר נגזרת מ-`lib/growth.ts` ולא מוקלדת כאן. החברה יושבת
 *   באתונה, והעיר הופיעה בשלב מסוים כ"תל אביב" — טעות עובדתית
 *   בקרדיט של החברה עצמה היא הפרט היחיד בעמוד שקורא יכול
 *   לתפוס בו את המוצר בשקר.
 */
export const IMPRINT_PREFIX = 'הובא לדפוס ע״י';
export const IMPRINT_PLACE = `בית הדפוס של דובל · ${DUBEL.city}, ${DUBEL.country}`;

/** השורה המלאה, לשימוש בטקסט חופשי (כרטיסים, שיתוף). */
export const IMPRINT = `${IMPRINT_PREFIX} ${DUBEL.name} · ${IMPRINT_PLACE}`;

/**
 * ההערה של המחזור.
 *
 * ★ `Math.abs` ו-`|| 0` אינם קישוט: `gameweekNumber` מגיע
 *   מהשרת, ומחזור 0 או מספר שלילי (מחזור הדגמה, באג בייבוא)
 *   היו מחזירים `undefined` מהמערך — כלומר שורה ריקה בתחתית
 *   העמוד, בלי שום שגיאה.
 */
export function pressNote(gameweekNumber: number): string {
  const n = Math.abs(Math.trunc(gameweekNumber || 0));
  return PRESS_NOTES[n % PRESS_NOTES.length];
}
