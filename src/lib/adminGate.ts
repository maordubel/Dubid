/**
 * lib/adminGate.ts — מי נכנס ללוח הניהול.
 *
 * ═══════════════════════════════════════════════════════════════
 * ★★ הבאג שהקובץ הזה קיים כדי שלא יחזור ★★
 * ═══════════════════════════════════════════════════════════════
 *
 * היו **שני מקורות אמת** ל"אני אדמין":
 *
 *   1. דגל ב-`sessionStorage`, שנקבע כשה-hash של הסיסמה תאם
 *      בדפדפן.
 *   2. `game.users.is_admin` במסד.
 *
 * שניים כאלה תמיד יסכימו — עד שלא. וזה בדיוק מה שקרה: הסיסמה
 * הייתה נכונה, השער המקומי הדליק את הדגל, **הקריאה לשרת נכשלה**,
 * והמשתמש נכנס. מאותו רגע:
 *
 *   · רענון הכניס אותו ישר פנימה, בלי לבקש סיסמה.
 *   · ובפנים — שום פעולה לא עבדה, כי במסד הוא לא אדמין.
 *
 * מסך פתוח שאי אפשר לעשות בו כלום הוא גרוע ממסך נעול. נעול
 * לפחות אומר לך מה לעשות.
 *
 * ═══════════════════════════════════════════════════════════════
 * ★ הכלל עכשיו: מקור אמת אחד — המסד.
 * ═══════════════════════════════════════════════════════════════
 *
 *     ready  ⇔  game.is_admin() החזירה true
 *
 * ולא "וגם", ולא "או". **אין דגל מקומי, ואין sessionStorage.**
 * אם המסד אומר לא — המסך נעול, גם אם הסיסמה הוקלדה נכון לפני
 * שנייה. אי אפשר להיכנס בלי הרשאה, ואי אפשר להיות בפנים בלעדיה.
 *
 * המחיר: בדיקה אחת ברשת בכל פתיחה של המסך. זה הוגן — היא לוקחת
 * פחות מהזמן שלוקח לקרוא את הכותרת.
 *
 * הקובץ הזה טהור בכוונה: בלי React, בלי דפדפן. המכונה עצמה
 * נבדקת (`tests/adminGate.test.ts`) בלי לפתוח מסך.
 */

/**
 * ★ שלושה מצבים, ואף אחד מהם אינו "אולי".
 *
 *   checking — הבדיקה רצה. **לא מציגים כלום.** מסך שמהבהב
 *              "אין הרשאה" ואז נפתח נראה שבור.
 *   locked   — המסד אמר לא. מציגים כניסה.
 *   ready    — המסד אמר כן. הכל פתוח, והכל יעבוד.
 */
export type AdminGate = 'checking' | 'locked' | 'ready';

export interface GateInput {
  /** מה שהמסד ענה. `null` = עוד לא ענה. */
  isDatabaseAdmin: boolean | null;
  /** האם הבדיקה הסתיימה (גם אם נכשלה). */
  checked: boolean;
}

/**
 * ★ שימו לב מה **לא** נמצא בקלט: שום דבר מקומי.
 *
 * אין `sessionStorage`, אין "הקלדתי סיסמה נכונה", ואין
 * "נכנסתי קודם". כל אחד מהם היה מחזיר את הבאג.
 */
export function resolveGate({ isDatabaseAdmin, checked }: GateInput): AdminGate {
  if (!checked) return 'checking';
  return isDatabaseAdmin === true ? 'ready' : 'locked';
}

/**
 * ★ כישלון רשת בבדיקה = נעול, לא פתוח.
 *
 * ברירת המחדל בספק חייבת להיות המחמירה. "לא הצלחתי לבדוק" אינו
 * "כן" — וכל מסך שמתייחס אליו ככן הוא מסך שנפתח למי שלא צריך.
 */
export function gateFromCheck(result: boolean | Error): AdminGate {
  return result === true ? 'ready' : 'locked';
}
